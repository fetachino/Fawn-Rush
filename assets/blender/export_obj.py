#!/usr/bin/env python3
"""Write .obj + .mtl for every Fawn Rush environment asset. Pure Python 3; no Blender required.

    python3 assets/blender/export_obj.py --out assets/export

The output is importable into Roblox Studio's 3D Importer or into Blender. It is the fast path: it
proves the geometry and the scale, and it is enough to replace a procedural prop with a real mesh.
The full path (materials, LODs, .blend, .fbx) is build_environment.py, which needs Blender.
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "lib"))

import meshlib  # noqa: E402


def write_mtl(path):
    lines = ["# Fawn Rush palette", "# 1 unit = 1 stud", ""]
    for name, (r, g, b) in sorted(meshlib.PALETTE.items()):
        lines.append("newmtl %s" % name)
        lines.append("Kd %.4f %.4f %.4f" % (r, g, b))
        lines.append("Ka 0 0 0")
        lines.append("Ks 0 0 0")
        lines.append("d 1.0")
        lines.append("illum 1")
        lines.append("")

    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))


def write_obj(name, path, mtl_name):
    vertices, faces, materials = meshlib.build_asset(name)

    lines = [
        "# %s — Fawn Rush" % name,
        "# 1 Blender unit = 1 stud. Origin at ground contact, centred laterally.",
        "# Generated by assets/blender/export_obj.py — do not hand-edit.",
        "# Y up, no normals or UVs: both Blender and the Roblox importer compute normals, and this",
        "# pipeline is flat palette colours rather than textured surfaces.",
        "mtllib %s" % mtl_name,
        "o %s" % name,
        "",
    ]

    for x, y, z in vertices:
        lines.append("v %.4f %.4f %.4f" % (x, y, z))

    lines.append("")

    current = None
    for face, material in zip(faces, materials):
        if material != current:
            lines.append("usemtl %s" % material)
            current = material
        # OBJ indices are 1-based.
        lines.append("f " + " ".join(str(index + 1) for index in face))

    lines.append("")

    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))

    return len(vertices), len(faces)


def main():
    parser = argparse.ArgumentParser(description="Export Fawn Rush environment meshes as OBJ/MTL")
    parser.add_argument("--out", default="assets/export", help="output directory")
    args = parser.parse_args()

    problems = meshlib.validate()
    if problems:
        for problem in problems:
            print("FAIL", problem, file=sys.stderr)
        print("Refusing to export an invalid asset set.", file=sys.stderr)
        return 1

    os.makedirs(args.out, exist_ok=True)
    mtl_name = "ENV_Palette.mtl"
    write_mtl(os.path.join(args.out, mtl_name))

    total_vertices = 0
    total_faces = 0

    for name in sorted(meshlib.ASSETS):
        vertex_count, face_count = write_obj(name, os.path.join(args.out, name + ".obj"), mtl_name)
        total_vertices += vertex_count
        total_faces += face_count
        print("%-28s %4d verts  %4d faces" % (name, vertex_count, face_count))

    print("\n%d assets, %d vertices, %d faces" % (len(meshlib.ASSETS), total_vertices, total_faces))
    print("Written to %s" % os.path.abspath(args.out))
    print("Import check: a 4-stud tile must measure exactly 4.00 studs in Studio.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
